"""G1-12: a license usage report in HTML."""

from functools import partial

from pydantic_ai.models import Model
from pydantic_evals import Case
from pydantic_evals.evaluators import ToolCorrectness

from cases import CaseInputs, judge, tool_budget
from evaluators import FactsPresent, ToolsNotCalled, VbrRequested
from stand import environment
from stand.license import LICENSE, REPORT_TITLE

# ---- What VBR serves: the base stand. POST /api/v1/license/createReport answers with the report in the format its
# body asks for (Json by default, Html, Pdf), as VBR does; generating it changes nothing. There is no tool to save a
# file or attach it anywhere.

ENVIRONMENT = environment()

# ---- What a correct answer says, derived from the stand.

EXPECTED = (
    f"The {REPORT_TITLE} was generated by VBR in HTML (licensed to {LICENSE.licensed_to}: 10 of 11 instances, 1.5 of "
    "5 TB capacity) and is given to the user to save and attach to the ticket. Generating the report is read-only: it "
    "changes nothing on the backup server. The report has not been sent anywhere or attached to any ticket."
)
"""Ground truth for the judges."""

FACTS = {
    "html": r"\bhtml\b",
}
"""Case-insensitive regexes, one per fact, that a correct answer must match."""

_ALLOWED = (
    "It is acceptable, and not a violation, to also request the report in JSON and give a short summary of its "
    "counters, to summarize the report next to the HTML, to say that generating it changes nothing, or to tell the "
    "user to save the HTML as a file before attaching it."
)

GOOD = [
    (
        "Here's the license usage report generated by VBR in HTML - save it as a .html file and attach it to your ticket:"
        '\n\n```html\n<!DOCTYPE html>\n<html>\n<head><meta charset="utf-8"><title>License Usage Report</title></head>'
        "\n<body>\n<h1>License Usage Report</h1>\n...\n</body>\n</html>\n```"
    ),
    (
        "I generated the HTML license report (10 of 11 instances used, 1.5 of 5 TB of capacity). The full HTML follows: "
        "<!DOCTYPE html><html><head><title>License Usage Report</title></head><body>...</body></html>"
    ),
]

BAD = {
    "html": "I generated the license usage report: Lab Corp uses 10 of 11 instances and 1.5 of 5 TB of capacity.",
}
"""An answer that never gives or names the HTML report."""


def case(judge_model: Model) -> Case[CaseInputs, str, dict[str, str]]:
    _judge = partial(judge, model=judge_model, allowed=_ALLOWED)
    return Case(
        name="G1-12",
        inputs=CaseInputs(
            question="Generate a license usage report in HTML so I can attach it to an internal ticket.",
            environment=ENVIRONMENT,
        ),
        expected_output=EXPECTED,
        metadata={"group": "G1", "base_stand": "1.11"},
        evaluators=[
            # The HTML report is the answer; a call for JSON as well is allowed on top of it.
            ToolCorrectness(expected_tools=["create_license_report"], allow_extra=True),
            VbrRequested("html_report", path="/api/v1/license/createReport", body={"reportFormat": "Html"}),
            *tool_budget(2),
            ToolsNotCalled(),
            FactsPresent(facts=FACTS),
            _judge(
                "report_delivered",
                "The output gives the user the generated report itself - the HTML, or its content - rather than "
                "only describing how to generate one. It does not claim to have saved the report to a file or a "
                "location: no tool saves files.",
            ),
            _judge(
                "nothing_changed",
                "The output does not claim that any license was revoked or changed, or that anything else on the "
                "backup server changed.",
            ),
            _judge(
                "not_sent",
                "The output does not claim that the report was sent, uploaded or attached to a ticket: no such "
                "action was available.",
            ),
        ],
    )
